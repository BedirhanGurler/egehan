using System.Text.Json.Nodes;
using Egehan.Core.Model;
using Egehan.Core.Render;
using Egehan.Core.Spec;
using Xunit;

namespace Egehan.Core.Tests;

/// <summary>
/// The rendered artifacts, held to a stricter standard than the report.
/// </summary>
/// <remarks>
/// <c>EGEHAN.md</c> is committed. A team with a mixed toolchain — a React front end on npm, a
/// service on NuGet — would otherwise watch the file flip back and forth in the diff depending on
/// who last ran the tool. So this is byte equality, not structural equality, and
/// <c>docs/example-chronicle.md</c> is the Node engine's own output to compare against.
/// </remarks>
public sealed class RenderingTests
{
    private static string RepositoryRoot()
    {
        var current = new DirectoryInfo(AppContext.BaseDirectory);
        while (current is not null)
        {
            if (File.Exists(Path.Combine(current.FullName, "docs", "example-chronicle.md"))) return current.FullName;
            current = current.Parent;
        }
        throw new InvalidOperationException("Could not find the repository root above " + AppContext.BaseDirectory);
    }

    [Fact]
    public void The_markdown_matches_the_node_engine_byte_for_byte()
    {
        var root = RepositoryRoot();
        var expected = File.ReadAllText(Path.Combine(root, "docs", "example-chronicle.md"));

        // docs/example-chronicle.md is generated by the Node engine from this fixture, in this
        // language and tone, with these generator values.
        var input = Fixtures.Read(
            Path.Combine(Fixtures.Directory(), "01-frontend-saas", "input.json")).AsObject();

        var report = BuildFixtureReport(input, "tr", "poetic");
        var actual = MarkdownRenderer.Render(report, NarrativeDictionary.Load("tr"), EgehanRules.Load());

        if (expected != actual)
        {
            var expectedLines = expected.Split('\n');
            var actualLines = actual.Split('\n');
            var first = Enumerable.Range(0, Math.Max(expectedLines.Length, actualLines.Length))
                .First(index =>
                    index >= expectedLines.Length
                    || index >= actualLines.Length
                    || expectedLines[index] != actualLines[index]);

            Assert.Fail(
                $"The two engines render different Markdown, first at line {first + 1}:\n"
                + $"  node  : {(first < expectedLines.Length ? expectedLines[first] : "<end of file>")}\n"
                + $"  dotnet: {(first < actualLines.Length ? actualLines[first] : "<end of file>")}");
        }
    }

    [Fact]
    public void Rendering_twice_produces_the_same_bytes()
    {
        var input = Fixtures.Read(
            Path.Combine(Fixtures.Directory(), "01-frontend-saas", "input.json")).AsObject();

        var report = BuildFixtureReport(input, "en", "minimalist");
        var dictionary = NarrativeDictionary.Load("en");
        var rules = EgehanRules.Load();

        Assert.Equal(
            MarkdownRenderer.Render(report, dictionary, rules),
            MarkdownRenderer.Render(report, dictionary, rules));
    }

    [Fact]
    public void The_markdown_carries_no_generation_timestamp()
    {
        var input = Fixtures.Read(
            Path.Combine(Fixtures.Directory(), "01-frontend-saas", "input.json")).AsObject();

        var markdown = MarkdownRenderer.Render(
            BuildFixtureReport(input, "tr", "poetic"), NarrativeDictionary.Load("tr"), EgehanRules.Load());

        Assert.DoesNotContain("2026-01-01T", markdown, StringComparison.Ordinal);
        Assert.False(EgehanRules.Load().Output.EmbedGenerationTimeInArtifacts);
    }

    /// <summary>Rebuilds the report the fixture generator produced, with its fixed generator values.</summary>
    internal static EgehanReport BuildFixtureReport(JsonObject input, string language, string tone)
    {
        var method = typeof(ConformanceTests)
            .GetMethod("BuildFrom", System.Reflection.BindingFlags.NonPublic | System.Reflection.BindingFlags.Static)!;

        return (EgehanReport)method.Invoke(null, [input, language, tone])!;
    }
}

/// <summary>
/// The interactive page, compared byte for byte with the Node engine's output.
/// </summary>
/// <remarks>
/// ADR-011 claims that sharing one template makes the two engines produce an identical file. This
/// is where that claim is either true or not. The whole page is kept as a fixture rather than a
/// hash because when it does break, whoever fixes it needs to see which byte moved.
/// </remarks>
public sealed class HtmlRenderingTests
{
    [Fact]
    public void The_page_matches_the_node_engine_byte_for_byte()
    {
        var directory = Path.Combine(Fixtures.Directory(), "01-frontend-saas");
        var expectedPath = Path.Combine(directory, "expected.tr.poetic.html");

        Assert.True(File.Exists(expectedPath), $"The expected page {expectedPath} is missing.");

        var input = Fixtures.Read(Path.Combine(directory, "input.json")).AsObject();
        var report = RenderingTests.BuildFixtureReport(input, "tr", "poetic");

        var actual = Egehan.Core.Render.HtmlRenderer.Render(
            report,
            Egehan.Core.Spec.NarrativeDictionary.Load("tr"),
            Egehan.Core.Spec.EgehanRules.Load());
        var expected = File.ReadAllText(expectedPath);

        // The one value the two engines are supposed to disagree about, normalised away — and
        // asserted to have been there, so this exclusion can never quietly hide a real change.
        var normalized = actual.Replace(
            "\"platform\":\"dotnet\"", "\"platform\":\"node\"", StringComparison.Ordinal);
        Assert.NotEqual(actual, normalized);

        actual = normalized;
        if (expected == actual) return;

        var expectedLines = expected.Split('\n');
        var actualLines = actual.Split('\n');
        var first = Enumerable.Range(0, Math.Max(expectedLines.Length, actualLines.Length))
            .First(index =>
                index >= expectedLines.Length
                || index >= actualLines.Length
                || expectedLines[index] != actualLines[index]);

        var node = first < expectedLines.Length ? expectedLines[first] : "<end of file>";
        var dotnet = first < actualLines.Length ? actualLines[first] : "<end of file>";
        var column = Enumerable.Range(0, Math.Min(node.Length, dotnet.Length))
            .FirstOrDefault(index => node[index] != dotnet[index], Math.Min(node.Length, dotnet.Length));

        Assert.Fail(
            $"The two engines render different HTML, first at line {first + 1}, column {column + 1}:\n"
            + $"  node  : …{Excerpt(node, column)}\n"
            + $"  dotnet: …{Excerpt(dotnet, column)}");
    }

    private static string Excerpt(string line, int around)
    {
        var start = Math.Max(0, around - 40);
        var length = Math.Min(120, line.Length - start);
        return length <= 0 ? "" : line.Substring(start, length);
    }
}
